export const ALL_CATALOG = {
  ...RETAINED_CATALOG,
  ...Object.fromEntries(IKEA_CATALOG.map((item) => [item.id, item])),
};

export function registerDynamicCatalogItem(item) {
  if (!item || !item.id) return null;
  const normalized = item.category === 'decor' ? { ...item, category: 'lighting' } : item;
  if (!ALL_CATALOG[normalized.id]) {
    ALL_CATALOG[normalized.id] = normalized;
  } else {
    Object.assign(ALL_CATALOG[normalized.id], normalized);
  }
  if (!IKEA_CATALOG.some((x) => x.id === normalized.id)) {
    IKEA_CATALOG.push(ALL_CATALOG[normalized.id]);
  }
  return ALL_CATALOG[normalized.id];
}

